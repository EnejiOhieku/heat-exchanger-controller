#!/usr/bin/env python3
"""
Heat Exchanger Web Asset Bundler
Inlines src/web/{index.html, style.css, app.js} into a single page, gzips it,
and writes src/network/web_dashboard.hpp as a PROGMEM byte array served with
Content-Encoding: gzip (about 4x smaller over the SoftAP link).
Also writes build/dashboard_preview.html for previewing in a desktop browser.
"""

import gzip
import os
import sys


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    src_dir = os.path.dirname(script_dir)
    repo_dir = os.path.dirname(src_dir)
    network_dir = os.path.join(src_dir, "network")
    output_hpp = os.path.join(network_dir, "web_dashboard.hpp")

    paths = {name: os.path.join(script_dir, name) for name in ("index.html", "style.css", "app.js")}
    missing = [p for p in paths.values() if not os.path.isfile(p)]
    if missing:
        print(f"Error: Missing web asset(s): {', '.join(missing)}", file=sys.stderr)
        sys.exit(1)

    def read(name):
        with open(paths[name], "r", encoding="utf-8") as f:
            return f.read()

    html, css, js = read("index.html"), read("style.css"), read("app.js")

    css_link = '<link rel="stylesheet" href="style.css">'
    js_link = '<script src="app.js"></script>'
    if css_link not in html or js_link not in html:
        print("Error: index.html must contain the style.css <link> and app.js <script> tags", file=sys.stderr)
        sys.exit(1)

    html = html.replace(css_link, f"<style>\n{css}\n</style>")
    html = html.replace(js_link, f"<script>\n{js}\n</script>")

    raw = html.encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)

    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")

    header = (
        "#pragma once\n\n"
        "// GENERATED by src/web/bundle.py - edit src/web/* instead.\n\n"
        "#include <Arduino.h>\n\n"
        f"// {len(raw)} bytes of HTML, gzip-compressed to {len(gz)} bytes\n"
        f"static const size_t PAGE_DASHBOARD_GZ_LEN = {len(gz)};\n"
        "static const uint8_t PAGE_DASHBOARD_GZ[] PROGMEM = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )

    os.makedirs(network_dir, exist_ok=True)
    with open(output_hpp, "w", encoding="utf-8") as f:
        f.write(header)

    preview_dir = os.path.join(repo_dir, "build")
    os.makedirs(preview_dir, exist_ok=True)
    with open(os.path.join(preview_dir, "dashboard_preview.html"), "w", encoding="utf-8") as f:
        f.write(html)

    print(f"✓ Bundled web assets into {output_hpp} ({len(raw)} B html -> {len(gz)} B gzip)")


if __name__ == "__main__":
    main()
