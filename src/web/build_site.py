#!/usr/bin/env python3
"""
Hosted-simulator site builder for the Heat Exchanger dashboard.

Inlines src/web/{index.html, style.css, simulator.js, app.js} into a single
self-contained page at docs/index.html. The page runs the plant model entirely
in the browser (src/web/simulator.js intercepts the /api/* calls), so it can be
served by any static host - GitHub Pages in particular.

A shared Gemini API key can be baked into the page so that every visitor uses it
(set once, no per-browser paste). It is read, in priority order, from:
    --api-key "KEY"   /  --model "MODEL"   command-line flags
    HX_GEMINI_API_KEY /  HX_GEMINI_MODEL   environment variables
    src/web/site.config.js                 (gitignored; see site.config.example.js)
The built page contains the key in plain text - restrict it in Google Cloud
Console and only bake a key you are willing to expose.

Usage:
    python3 src/web/build_site.py
    HX_GEMINI_API_KEY=AIza... python3 src/web/build_site.py
    python3 src/web/build_site.py --api-key AIza... --with-copy
"""

import gzip
import json
import os
import re
import sys


def site_config_snippet(script_dir):
    """HTML <script> defining window.HX_SITE_CONFIG for the hosted page.

    Returns (snippet, was_baked). When no key is supplied the snippet defines an
    empty config and visitors are asked for their own key (stored per-browser).
    """
    api_key = os.environ.get("HX_GEMINI_API_KEY", "").strip()
    model = os.environ.get("HX_GEMINI_MODEL", "").strip()
    args = sys.argv[1:]
    for i, a in enumerate(args):
        if a == "--api-key" and i + 1 < len(args):
            api_key = args[i + 1].strip()
        elif a == "--model" and i + 1 < len(args):
            model = args[i + 1].strip()

    if api_key:
        cfg = json.dumps({"apiKey": api_key, "model": model})
        return "<script>window.HX_SITE_CONFIG = %s;</script>\n" % cfg, True

    cfg_path = os.path.join(script_dir, "site.config.js")
    if os.path.isfile(cfg_path):
        with open(cfg_path, "r", encoding="utf-8") as f:
            text = f.read()
        m = re.search(r"apiKey\s*:\s*['\"]([^'\"]+)['\"]", text)
        baked = bool(m and m.group(1).strip())
        return "<script>\n" + text + "\n</script>\n", baked

    return "<script>window.HX_SITE_CONFIG = { apiKey: '', model: '' };</script>\n", False


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    src_dir = os.path.dirname(script_dir)
    repo_dir = os.path.dirname(src_dir)
    docs_dir = os.path.join(repo_dir, "docs")
    output_html = os.path.join(docs_dir, "index.html")

    names = ("index.html", "style.css", "simulator.js", "app.js")
    paths = {n: os.path.join(script_dir, n) for n in names}
    missing = [p for p in paths.values() if not os.path.isfile(p)]
    if missing:
        print("Error: Missing web asset(s): " + ", ".join(missing), file=sys.stderr)
        sys.exit(1)

    def read(name):
        with open(paths[name], "r", encoding="utf-8") as f:
            return f.read()

    html, css, sim, app = (read("index.html"), read("style.css"), read("simulator.js"), read("app.js"))

    css_link = '<link rel="stylesheet" href="style.css">'
    app_script = '<script src="app.js"></script>'
    if css_link not in html or app_script not in html:
        print("Error: index.html must contain the style.css <link> and app.js <script> tags",
              file=sys.stderr)
        sys.exit(1)

    html = html.replace(css_link, "<style>\n" + css + "\n</style>")
    # Shared site config first, then the simulator (it must define the fetch
    # shim before app.js runs), then the dashboard.
    config_snippet, baked = site_config_snippet(script_dir)
    html = html.replace(app_script, config_snippet + "<script>\n" + sim +
                        "\n</script>\n<script>\n" + app + "\n</script>")

    banner = ("<!-- Hosted client-side simulator. Generated by src/web/build_site.py; "
              "edit src/web/* and rebuild instead of editing this file. -->\n")
    html = banner + html

    os.makedirs(docs_dir, exist_ok=True)
    with open(output_html, "w", encoding="utf-8") as f:
        f.write(html)

    # Tell GitHub Pages not to run Jekyll on the folder.
    nojekyll = os.path.join(docs_dir, ".nojekyll")
    if not os.path.exists(nojekyll):
        open(nojekyll, "w").close()

    raw = html.encode("utf-8")
    print("Built %s (%d bytes HTML, %.1f kB gzip)" % (
        output_html, len(raw), len(gzip.compress(raw, 9)) / 1024.0))
    print("Shared API key: " + ("baked into the page (used by every visitor)"
                                if baked else "not set (each visitor pastes their own key)"))

    if "--with-copy" in sys.argv:
        # Convenience: also drop a copy for the portfolio repo.
        alt = os.path.join(repo_dir, "build", "heat-sim.html")
        os.makedirs(os.path.dirname(alt), exist_ok=True)
        with open(alt, "w", encoding="utf-8") as f:
            f.write(html)
        print("Also wrote %s" % alt)


if __name__ == "__main__":
    main()