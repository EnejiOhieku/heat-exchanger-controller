#!/usr/bin/env python3
"""
Hosted-simulator site builder for the Heat Exchanger dashboard.

Inlines src/web/{index.html, style.css, simulator.js, app.js} into a single
self-contained page at docs/index.html. The page runs the plant model entirely
in the browser (src/web/simulator.js intercepts the /api/* calls), so it can be
served by any static host - GitHub Pages in particular.

Usage:
    python3 src/web/build_site.py
"""

import gzip
import os
import sys


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    src_dir = os.path.dirname(script_dir)
    repo_dir = os.path.dirname(src_dir)
    docs_dir = os.path.join(repo_dir, "docs")
    output_html = os.path.join(docs_dir, "index.html")

    names = ("index.html", "style.css", "simulator.js", "app.js")
    paths = {n: os.path.join(script_dir, n) for n in names}
    missing = [p for p in paths.values() if not os.path.isfile(p)]
    if missing:
        print("Error: Missing web asset(s): " + ", ".join(missing), file=sys.stderr)
        sys.exit(1)

    def read(name):
        with open(paths[name], "r", encoding="utf-8") as f:
            return f.read()

    html, css, sim, app = (read("index.html"), read("style.css"), read("simulator.js"), read("app.js"))

    css_link = '<link rel="stylesheet" href="style.css">'
    app_script = '<script src="app.js"></script>'
    if css_link not in html or app_script not in html:
        print("Error: index.html must contain the style.css <link> and app.js <script> tags",
              file=sys.stderr)
        sys.exit(1)

    html = html.replace(css_link, "<style>\n" + css + "\n</style>")
    # Simulator must define the fetch shim before app.js runs.
    html = html.replace(app_script, "<script>\n" + sim + "\n</script>\n<script>\n" + app + "\n</script>")

    banner = ("<!-- Hosted client-side simulator. Generated by src/web/build_site.py; "
              "edit src/web/* and rebuild instead of editing this file. -->\n")
    html = banner + html

    os.makedirs(docs_dir, exist_ok=True)
    with open(output_html, "w", encoding="utf-8") as f:
        f.write(html)

    # Tell GitHub Pages not to run Jekyll on the folder.
    nojekyll = os.path.join(docs_dir, ".nojekyll")
    if not os.path.exists(nojekyll):
        open(nojekyll, "w").close()

    raw = html.encode("utf-8")
    print("Built %s (%d bytes HTML, %.1f kB gzip)" % (
        output_html, len(raw), len(gzip.compress(raw, 9)) / 1024.0))

    if "--with-copy" in sys.argv:
        # Convenience: also drop a copy for the portfolio repo.
        alt = os.path.join(repo_dir, "build", "heat-sim.html")
        os.makedirs(os.path.dirname(alt), exist_ok=True)
        with open(alt, "w", encoding="utf-8") as f:
            f.write(html)
        print("Also wrote %s" % alt)


if __name__ == "__main__":
    main()